
//  Builds and downloads a plain-text analysis report.


const AlignReport = (() => {

  // ---------- helpers ----------
  function line(char, len) {
    return (char || "=").repeat(len || 60);
  }

  function heading(text) {
    return `\n${line("=")}\n  ${text}\n${line("=")}\n`;
  }

  function subheading(text) {
    return `\n${line("-")}\n  ${text}\n${line("-")}\n`;
  }

  function bulletList(items) {
    if (!items || !items.length) return "  (none)\n";
    return items.map((s) => `  - ${s}`).join("\n") + "\n";
  }

  // ---------- buildText ----------
  function buildText(data, meta) {
    const { match, info, insights, ai, ai_error: aiError } = data;
    const { fileName, jdSnippet, createdAt } = meta;

    const dateStr = new Date(createdAt).toLocaleString("en-US", {
      year: "numeric", month: "long", day: "numeric",
      hour: "2-digit", minute: "2-digit"
    });

    let out = "";

    // Title block
    out += line("=") + "\n";
    out += "  AlignCV \u2013 Analysis Report\n";
    out += line("=") + "\n";
    out += `  Generated : ${dateStr}\n`;
    out += `  Resume    : ${fileName}\n`;
    out += `  JD Snippet: ${jdSnippet ? jdSnippet.slice(0, 100) : "(not provided)"}\n`;
    out += line("=") + "\n";

    // Match score
    out += heading("MATCH SCORE");
    out += `  Score          : ${Math.round(match.score)} / 100  (${match.label})\n`;
    if (match.skill_match_ratio !== null) {
      out += `  Skill match    : ${Math.round(match.skill_match_ratio * 100)}%\n`;
    }
    out += `  Text similarity: ${Math.round(match.tfidf_similarity * 100)}%\n`;

    // Skills
    out += heading("SKILLS");

    out += subheading("Matched Skills (present in both resume and job description)");
    out += bulletList(match.skills.matched);

    out += subheading("Missing Skills (required by job, not found in resume)");
    out += bulletList(match.skills.missing);

    out += subheading("Extra Skills in Resume");
    out += bulletList(match.skills.extra);

    // Resume skills by category
    out += heading("RESUME SKILLS BY CATEGORY");
    const techGroups = Object.entries(info.skills.technical);
    if (techGroups.length) {
      techGroups.forEach(([cat, items]) => {
        out += `\n  [${cat}]\n`;
        out += bulletList(items);
      });
    } else {
      out += "  (no technical skills detected)\n";
    }
    if (info.skills.soft && info.skills.soft.length) {
      out += "\n  [Soft Skills]\n";
      out += bulletList(info.skills.soft);
    }

    // Insights
    out += heading("INSIGHTS");

    out += subheading("Strengths");
    out += bulletList(insights.strengths);

    out += subheading("Areas for Improvement");
    out += bulletList(insights.improvements);

    // Resume sections detected
    out += heading("RESUME SECTIONS DETECTED");
    out += bulletList(info.sections_found && info.sections_found.length
      ? info.sections_found
      : ["(no sections listed)"]);

    // AI suggestions
    out += heading("AI SUGGESTIONS");

    if (!ai) {
      out += "  AI suggestions were unavailable for this analysis.\n";
      if (aiError) out += `  Reason: ${aiError}\n`;
    } else {
      out += subheading("Summary");
      out += `  ${ai.summary || "(no summary)"}\n`;

      out += subheading("Improvement Suggestions");
      out += bulletList(ai.improvement_suggestions);

      out += subheading("Skills to Work On");
      if (ai.skills_to_add && ai.skills_to_add.length) {
        ai.skills_to_add.forEach(({ skill, how }) => {
          out += `  - ${skill}`;
          if (how) out += `: ${how}`;
          out += "\n";
        });
      } else {
        out += "  (none)\n";
      }

      out += subheading("Before / After Bullet Rewrites");
      if (ai.rewritten_bullets && ai.rewritten_bullets.length) {
        ai.rewritten_bullets.forEach(({ original, improved }) => {
          out += `  BEFORE: ${original}\n`;
          out += `  AFTER : ${improved}\n\n`;
        });
      } else {
        out += "  (no rewrites suggested)\n";
      }

      out += subheading("Keywords to Include");
      out += bulletList(ai.keywords_to_include);
    }

    // Footer
    out += "\n" + line("=") + "\n";
    out += "  This report was generated by AlignCV.\n";
    out += "  Review all AI suggestions critically before applying them.\n";
    out += line("=") + "\n";

    return out;
  }

  // ---------- download ----------
  function download(data, meta) {
    const text = buildText(data, meta);
    const blob = new Blob([text], { type: "text/plain;charset=utf-8" });
    const url  = URL.createObjectURL(blob);

    const dateTag = new Date(meta.createdAt).toISOString().slice(0, 10);
    const filename = `AlignCV-report-${dateTag}.txt`;

    const a = document.createElement("a");
    a.href     = url;
    a.download = filename;
    a.style.display = "none";
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  }

  return { buildText, download };
})();
